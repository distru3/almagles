/** Strips tashkeel and tatweel and folds letter variants, so «القُرآن» matches «قران». */
export function normalizeArabic(s: string): string {
  return s
    .replace(/[ً-ٰٟۖ-ۭـ]/g, '')
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ي')
    .toLowerCase();
}

const PREFIXES = ['وبال', 'وال', 'بال', 'فال', 'كال', 'لل', 'ال', 'و', 'ف', 'ب', 'ل'];

/** A word plus its forms with a leading و / ف / ب / ل / ال taken off. */
function forms(word: string): string[] {
  const out = [word];
  for (const p of PREFIXES) if (word.startsWith(p) && word.length - p.length >= 2) out.push(word.slice(p.length));
  return out;
}

const tokenize = (s: string) => normalizeArabic(s).split(/[^\p{L}\p{N}]+/u).filter(Boolean);

/** Entries whose keywords appear in the task, most specific first, at most `limit`. */
export function fadailFor(text: string, limit = 2): Fadl[] {
  const tokens = tokenize(text);
  if (tokens.length === 0) return [];
  const words = new Set(tokens.flatMap(forms));
  const phrase = ` ${tokens.join(' ')} `;
  const hits = FADAIL.filter((f) =>
    f.keywords.some((k) => {
      const kw = tokenize(k);
      if (kw.length > 1) return phrase.includes(` ${kw.join(' ')} `);
      return words.has(kw[0]);
    }),
  );
  // A task about «سورة الكهف» shouldn't also get the general Qur'an entry.
  const specific = hits.some((f) => f.id === 'kahf' || f.id === 'mulk' || f.id === 'hifz');
  return hits.filter((f) => !(specific && f.id === 'quran')).slice(0, limit);
}
