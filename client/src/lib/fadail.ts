/**
 * «فضائل الأعمال»: what the Qur'an and the Sunnah say about the reward of a
 * deed. A task whose title or details mention one of an entry's keywords shows
 * that entry to members (under «فضلها», and as good news when they tick it).
 *
 * Only well-known authentic texts, each with its source. To add a deed, add an
 * entry: `keywords` are matched as whole words (with ال / و / ف / ب / ل in front
 * allowed) after the text is normalised — no tashkeel, أ/إ/آ → ا, ة → ه, ى → ي —
 * so write them normalised. A keyword with a space is matched as a phrase.
 * More specific entries go first; a task shows at most two.
 */

export interface Text {
  kind: 'ayah' | 'hadith';
  text: string;
  source: string;
}

export interface Fadl {
  id: string;
  /** What the deed is called, e.g. «قيام الليل». */
  title: string;
  keywords: string[];
  texts: Text[];
}

const ayah = (text: string, source: string): Text => ({ kind: 'ayah', text, source });
const hadith = (text: string, source: string): Text => ({ kind: 'hadith', text, source });

