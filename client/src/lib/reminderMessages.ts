/** The list label: the text without diacritics, cut short so the menu stays readable. */
export function presetLabel(p: ReminderPreset): string {
  const plain = p.text.replace(/[ً-ْٰۖ-ۭ]/g, '').replace(/^قال ﷺ: /, '');
  return plain.length > 70 ? `${plain.slice(0, 70)}…` : plain;
}
